# 1. Pedimos el nombre completo al usuario
nombre_completo = input("Introduce tu nombre completo: ")

# 2. Mostramos el nombre en minúsculas
print(nombre_completo.lower())

# 3. Mostramos el nombre en mayúsculas
print(nombre_completo.upper())

# 4. Mostramos el nombre con la primera letra de cada palabra en mayúscula
print(nombre_completo.title())